CREATE DATABASE IF NOT EXISTS pg_finder CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE pg_finder;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  phone VARCHAR(15) NOT NULL,
  password VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS listings (
  id INT AUTO_INCREMENT PRIMARY KEY,
  owner_id INT NOT NULL,
  title VARCHAR(150) NOT NULL,
  type ENUM('PG','Hostel') NOT NULL,
  gender ENUM('Boys','Girls','Any') NOT NULL DEFAULT 'Any',
  city VARCHAR(80) NOT NULL,
  area VARCHAR(100) NOT NULL,
  address VARCHAR(255) NOT NULL,
  map_link VARCHAR(500) DEFAULT NULL,
  rent INT NOT NULL,
  deposit INT NOT NULL DEFAULT 0,
  sharing TINYINT NOT NULL DEFAULT 1,
  amenities VARCHAR(255) DEFAULT '',
  description TEXT,
  contact_phone VARCHAR(15) NOT NULL,
  image VARCHAR(255) DEFAULT NULL,
  is_available TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE,
  INDEX (city), INDEX (type), INDEX (rent)
);
